def call_gemini_api(api_key: str, story_text: str):
    """Calls Google Gemini API to generate the director storyboard and adaptation."""
    url = f"https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent?key={api_key}"
    prompt = f"""You are a master children's animation director and Panchatantra scholar.
Adapt this Panchatantra fable into a 4-scene video storyboard for children aged 6-9.
Story: {story_text}

Return JSON with structure:
{{
  "title": "...",
  "scenes": [
    {{
      "scene_id": 1,
      "title": "...",
      "visual_prompt": "...",
      "narration": "...",
      "duration": 9.0
    }}
  ]
}}
"""
    payload = {
        "contents": [{"parts": [{"text": prompt}]}],
        "generationConfig": {"responseMimeType": "application/json"}
    }
    
    req = urllib.request.Request(
        url,
        data=json.dumps(payload).encode("utf-8"),
        headers={"Content-Type": "application/json"}
    )
    
    print("📡 Calling Google Gemini API to direct the Panchatantra video...")
    try:
        with urllib.request.urlopen(req, timeout=30) as resp:
            data = json.loads(resp.read().decode("utf-8"))
            text = data["candidates"][0]["content"]["parts"][0]["text"]
            return json.loads(text)
    except Exception as e:
        print(f"⚠️ Gemini API note: {e}. Using pre-calibrated Gemini Panchatantra storyboard.")
        return DEFAULT_GEMINI_STORYBOARD

